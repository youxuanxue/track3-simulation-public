def _run_isolated(scen_path: Path, out_dir: Path) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    r = subprocess.run(
        [
            "docker",
            "run",
            "--rm",
            "--network=none",
            "-v",
            f"{scen_path}:/input/scenario.json:ro",
            "-v",
            f"{out_dir}:/output",
            IMAGE,
            "simulate",
            "--config",
            "/input/scenario.json",
            "--out",
            "/output/trace.parquet",
        ],
        capture_output=True,
        text=True,
    )
    if r.returncode != 0:
        raise RuntimeError(r.stderr[-400:])
    return json.loads((out_dir / "events.json").read_text())


