def _apply(overrides: dict) -> dict:
    cfg = copy.deepcopy(_SUB_BASE)
    for path, val in overrides.items():
        parts = path.split(".")
        node = cfg
        for p in parts[:-1]:
            node = node[int(p)] if p.isdigit() else node[p]
        last = parts[-1]
        if last.isdigit():
            node[int(last)] = val
        else:
            node[last] = val
    return cfg


def _det_seed(s: str) -> int:
    return int(hashlib.sha256(s.encode()).hexdigest(), 16) % (2**31 - 1) + 1


def _det_uuid(s: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "t3-v2-batchsub-" + s))


def _sha(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


