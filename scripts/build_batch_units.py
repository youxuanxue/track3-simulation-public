def _write_manifest(unit_dir: Path, unit_id: str) -> None:
    files = []
    for path in sorted(unit_dir.rglob("*")):
        if path.is_dir() or path.name == "manifest.json":
            continue
        rel = path.relative_to(unit_dir).as_posix()
        role = (
            "scenario"
            if rel.startswith("scenarios/")
            else "reference"
            if rel.startswith("checks/reference_data/")
            else "fixture"
        )
        files.append(
            {
                "path": rel,
                "role": role,
                "license": "CC-BY-4.0",
                "sha256": _sha(path),
                "split": "public-dev",
                "redistributable": True,
                "bytes": path.stat().st_size,
            }
        )
    (unit_dir / "manifest.json").write_text(
        json.dumps(
            {
                "manifest_version": "2.0",
                "unit_id": unit_id,
                "generated_by": "scripts/build_batch_units.py",
                "files": files,
                "notes": f"Public-dev BatchMarketSim unit {unit_id}; real sha256/bytes for every file.",
            },
            indent=2,
        )
        + "\n"
    )


def main() -> int:
    reg = json.loads(REGISTRY.read_text())
    built = []
    for name, subs in _DESIGNS.items():
        unit_id = "t3-" + name
        unit_dir = UNITS / unit_id
        # clean any prior build so removed subs don't linger
        if unit_dir.exists():
            import shutil

            shutil.rmtree(unit_dir)
        (unit_dir / "scenarios").mkdir(parents=True)
        (unit_dir / "checks" / "reference_data").mkdir(parents=True)
        batch_entries = []
        for sub_name, overrides in subs:
            slug = f"{name}-{sub_name}"
            cfg = _apply(overrides)
            cfg.update({"scenario_id": _det_uuid(slug), "seed": _det_seed(slug)})
            scen_path = unit_dir / "scenarios" / f"{sub_name}.json"
            scen_path.write_text(json.dumps(cfg, indent=2) + "\n")
            ref_dir = unit_dir / "checks" / "reference_data" / sub_name
            ev = _run_isolated(scen_path, ref_dir)
            batch_entries.append(
                {
                    "sub": sub_name,
                    "scenario_file": f"scenarios/{sub_name}.json",
                    "n_events": int(ev["n_events"]),
                    "reference_trace_sha256": _sha(ref_dir / "trace.parquet"),
                    "reference_message_sha256": _sha(ref_dir / "message_trace.parquet"),
                }
            )
        (unit_dir / "batch.json").write_text(
            json.dumps({"n": len(subs), "subs": batch_entries}, indent=2) + "\n"
        )
        canary = reg["units"].setdefault(unit_id, str(uuid.uuid4()))
        (unit_dir / "card.toml").write_text(_card(unit_id, len(subs), canary))
        _write_manifest(unit_dir, unit_id)
        total = sum(e["n_events"] for e in batch_entries)
        print(f"  built {unit_id}: {len(subs)} subs, {total} total events")
        built.append(unit_id)
    REGISTRY.write_text(json.dumps(reg, indent=2) + "\n")
    print(f"built {len(built)} public batch units: {built}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
