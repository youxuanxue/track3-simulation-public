"""Author the public BatchMarketSim (GB) units — batched multi-scenario practice packages.

Each batch unit bundles N independent single-market sub-scenarios plus their ISOLATED reference
traces (generated by running each sub alone through the ledger baseline). A submission runs the
batch verb `simulate-batch` over ``scenarios/`` and must reproduce every sub's isolated reference;
a batch that leaks state across markets diverges on some sub and fails the isolation gate. The
aggregate events/sec across the batch is the throughput the family ranks.

Unit layout (self-contained; validate_units-compatible — card + manifest + unique canary):

    units/t3-gbatch-<name>/
      card.toml            scenario_family=throughput-scale (fam 6, Tier-A); [batch] batch=true, n=N
      batch.json           {"n": N, "subs": [{"sub","scenario_file","reference_trace_sha256",
                                              "reference_message_sha256","n_events"}]}
      scenarios/<sub>.json           N solver-facing sub-scenarios (only solver-facing artifacts)
      checks/reference_data/<sub>/trace.parquet + message_trace.parquet + events.json
                                     N isolated references
      manifest.json

Usage:  python scripts/build_batch_units.py        # regenerates every public gbatch unit
Reference generation uses the pinned ledger image (track3-abides-ledger:test), --network=none.
"""

